# Timeouts are classified by exception TYPE (ticket 16): KicadRoutingToolsTimeout and
# FreeroutingTimeout are raised only when the subprocess was really killed at its cap.
_FREEROUTING_PROBE_TIMEOUT_S = 60


def _sha256_file(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


# --- invariants -------------------------------------------------------------------------------


def board_invariants(board_path: str | Path) -> dict[str, Any]:
    """Fingerprints of everything a routing attempt must leave alone, from the raw
    parsed S-expression (never from convenience properties):

    * ``placement``: footprints in full (position, layer, pads, pad nets);
    * ``nets``: the net table; ``setup``: board setup and layer stack;
    * ``graphics``: board graphics (outline, text);
    * ``zones``: zone and keepout / rule-area OUTLINES and settings, not their fill;
    * ``copper``: a "must still contain" set of the segments, vias and arcs that were in
      the input (the router's added copper is not in the input, so it is allowed).

    Still excluded, deliberately: filled polygons (a fill is regenerated by the gate),
    a zone the ticket-04 pour step legitimately carries in (it will need an explicit
    allowance when that path is wired into attempts), the title block, and properties
    and uuids of anything not listed above.
    """
    from kicad_tools.sexp import parse_file

    root = parse_file(str(board_path))

    def digest(texts: list[str]) -> str:
        h = hashlib.sha256()
        for text in texts:
            h.update(text.encode("utf-8"))
            h.update(b"\x00")
        return h.hexdigest()

    children = list(root.children)

    def zone_outline(node: Any) -> str:
        kept = [c.to_string() for c in node.children if c.name not in ("filled_polygon", "island")]
        # (``node.values`` also lists child nodes, so it is deliberately not used.)
        return "|".join([str(node.name), *kept])

    return {
        "placement": digest([c.to_string() for c in children if c.name == "footprint"]),
        "nets": digest([c.to_string() for c in children if c.name == "net"]),
        "setup": digest([c.to_string() for c in children if c.name in ("setup", "layers")]),
        "graphics": digest([c.to_string() for c in children if str(c.name).startswith("gr_")]),
        "zones": digest([zone_outline(c) for c in children if c.name == "zone"]),
        "copper": {
            "kind": "superset",
            "items": sorted(
                hashlib.sha256(c.to_string().encode("utf-8")).hexdigest()
                for c in children if c.name in ("segment", "via", "arc")
            ),
        },
    }


# --- availability -----------------------------------------------------------------------------


def krt_availability() -> dict:
    """Honest availability of KiCadRoutingTools: checkout, interpreter packages, the
    prebuilt Rust router, and the pinned CLI snapshot. A version that differs from the
    snapshot is reported (the run becomes unofficial); a flag the wrapper emits that the
    snapshot lacks makes the backend unavailable."""
    try:
        status = krt_tools.check_availability()
    except Exception as exc:  # noqa: BLE001 - availability must never raise
        return {"backend": "krt", "available": False, "reason": f"availability probe failed: {exc}"}
    if status.get("status") != "complete":
        return {"backend": "krt", "available": False, "reason": status.get("reason"), "details": status}
    try:
        snapshot = krt_tools.load_cli_snapshot()
        missing = krt_tools.check_emitted_flags(snapshot)
        version = krt_tools.router_version(status["checkout"])
        version_check = krt_tools.compare_router_version(snapshot, version)
    except krt_tools.KicadRoutingToolsError as exc:
        return {"backend": "krt", "available": False, "reason": str(exc)}
    if missing:
        flags = ", ".join(m["flag"] for m in missing)
        return {"backend": "krt", "available": False,
                "reason": f"router CLI snapshot lacks flags the wrapper emits: {flags}"}
    return {
        "backend": "krt",
        "available": True,
        "reason": None,
        "versions": {"router": version, "grid_router": status.get("grid_router_version"),
                     "router_python": status.get("python_version")},
        "version_check": version_check,
    }


# Freerouting prints this banner as its first log line, before ``-help`` is handled
# ("Freerouting v2.5.0 (build-date: 2026-10-05)"); it is English in every locale.
_FREEROUTING_VERSION_RE = re.compile(r"\bFreerouting v(\d+(?:\.\d+)+[^\s()]*)")


def _freerouting_probe() -> tuple[str | None, str | None]:
    """``(problem, version)``: ``problem`` is None if Java and the jar are present, the JVM
    can load the jar and its banner names a version, else why not.

    The output is decoded explicitly (``decode_jvm_output``), so a Python in UTF-8 mode no
    longer loses it to a ``UnicodeDecodeError`` on a German JVM's Cp1252 help text and then
    reports available unchecked (paradigm-review-2 ticket 01). The probe runs in its own
    sandbox, like every Freerouting run (build ticket 33)."""
    try:
        java = routing_toolset.find_java()
        jar = routing_toolset.find_freerouting_jar()
    except routing_toolset.FreeroutingError as exc:
        return str(exc), None
    try:
        with routing_toolset.freerouting_sandbox() as sandbox:
            proc = subprocess.run(
                routing_toolset.freerouting_command(java, jar, sandbox, "-help"), capture_output=True,
                check=False, timeout=_FREEROUTING_PROBE_TIMEOUT_S, cwd=sandbox,
            )
    except (OSError, subprocess.SubprocessError) as exc:
        return f"could not start {java} -jar {jar}: {exc}", None
    text = (f"{routing_toolset.decode_jvm_output(proc.stdout)}\n"
            f"{routing_toolset.decode_jvm_output(proc.stderr)}")
    for marker in ("UnsupportedClassVersionError", "Unable to access jarfile", "Error: Invalid or corrupt jarfile"):
        if marker in text:
            return f"the JVM at {java} cannot run {jar}: {marker}", None
    excerpt = " ".join(text.split())
    if proc.returncode != 0:
        # The banner is printed before -help is handled, so a JVM that dies afterwards
        # (NoClassDefFoundError, OutOfMemoryError, ...) still shows it. Freerouting 2.5.0's
        # -help exits 0; anything else is not a usable install.
        return (f"{jar} -help failed (exit {proc.returncode}; a usable install exits 0): "
                f"{excerpt[-300:]!r}"), None
    match = _FREEROUTING_VERSION_RE.search(text)
    if match is None:
        return (f"could not read the Freerouting version from {jar} -help "
                f"(exit {proc.returncode}): {excerpt[:300]!r}"), None
    return None, match.group(1)


def _kicad_specctra_problem() -> tuple[str | None, dict]:
    """``(problem, info)``: the Freerouting path needs KiCad's bundled Python with ``pcbnew``
    for its DSN export and SES import (build ticket 46). Without it the backend is
    unavailable; there is no fallback DSN writer."""
    info = routing_toolset.kicad_specctra_availability()
    if not info["available"]:
        return f"KiCad's Specctra export/import is not usable: {info['reason']}", info
    return None, info


def _freerouting_ready() -> str | None:
    """None if Java and the jar are present, the JVM can load the jar and it reports its
    version, and KiCad's bundled Python can import ``pcbnew``, else why not."""
    return _freerouting_probe()[0] or _kicad_specctra_problem()[0]


def freerouting_availability() -> dict:
    """Freerouting is GPLv3 and never bundled: it needs a JVM and a jar named by
    ``FREEROUTING_JAR_PATH``, and KiCad's bundled Python for the DSN and SES. Missing any of
    them, or a jar whose version cannot be read, is UNAVAILABLE for the whole batch."""
    problem, version = _freerouting_probe()
    if problem is not None:
        return {"backend": "freerouting", "available": False, "reason": problem}
    kicad_problem, kicad = _kicad_specctra_problem()
    if kicad_problem is not None:
        return {"backend": "freerouting", "available": False, "reason": kicad_problem}
    java = routing_toolset.find_java()
    jar = routing_toolset.find_freerouting_jar()
    return {
        "backend": "freerouting",
        "available": True,
        "reason": None,
        "versions": {"java": str(java), "freerouting": version, "freerouting_jar": str(jar),
                     "freerouting_jar_sha256": _sha256_file(jar),
                     "kicad_python": kicad.get("python"), "pcbnew": kicad.get("pcbnew_version")},
    }


def availability(backend_name: str) -> dict:
    if backend_name == "krt":
        return krt_availability()
    if backend_name == "freerouting":
        return freerouting_availability()
    return {"backend": backend_name, "available": False, "reason": f"unknown backend {backend_name!r}"}


def tool_versions(backend_name: str, info: dict | None = None) -> dict:
    """Versions recorded in the frozen manifest: the gate's source, kicad-cli,
    kicad_tools and the backend's tool. Unknown stays ``None``, never guessed. ``info`` is
    the availability result the caller already has (one probe per measurement)."""
    from kicad_mcp import verify_board

    versions: dict[str, Any] = {
        "python": sys.version.split()[0],
        "verify_board_sha256": _sha256_file(Path(verify_board.__file__)),
        "autonomy_protocol_sha256": rung_runner.protocol_sha256(),
        "kicad_cli": None,
        "kicad_tools": None,
    }
    try:
        from kicad_mcp import kicad_cli

        proc = subprocess.run([str(kicad_cli.find_kicad_cli()), "version"], capture_output=True,
                              text=True, timeout=30, check=False)
        versions["kicad_cli"] = proc.stdout.strip() or None
    except Exception:  # noqa: BLE001
        pass
    try:
        import importlib.metadata as md

        versions["kicad_tools"] = md.version("kicad-tools")
    except Exception:  # noqa: BLE001
        pass
    info = info if info is not None else availability(backend_name)
    versions["backend_available"] = info.get("available", False)
    versions.update(info.get("versions") or {})
    return versions


def pour_warnings(zones: list[dict], expected: set[tuple[str, str]] | None) -> list[dict]:
    """Warnings (never unofficial reasons) for outline-only pours the run was not told to
    expect. With no expectation given, every pour warns: provenance is structural only."""
    out = []
    for zone in zones:
        if expected is not None and (zone["net"], zone["layer"]) in expected:
            continue
        message = (f"pour {zone['net'] or '<no net>'}/{zone['layer']} is outline-only and was not "
                   "verified as pour-step output (structural allowance)")
        if not zone["net"]:
            message += "; it carries no net"
        if zone.get("embedded_in"):
            message += f"; it is embedded in footprint {zone['embedded_in']}"
        out.append({"net": zone["net"], "layer": zone["layer"], "message": message})
    return out


def unofficial_reasons(info: dict) -> list[str]:
    """Reasons the backend's tool state (an availability result) makes a run unofficial."""
    check = info.get("version_check") or {}
    if info.get("available") and check and not check.get("matches", True):
        return [str(check.get("message"))]
    return []


def input_refusal(board: str | Path) -> str | None:
    """Setup preflight: why this input is refused before any attempt (None = accepted).
    Same for both routers, so it is a batch-level refusal, never five failed attempts."""
    return _pour_problem(Path(board))


# --- shared adapter pieces --------------------------------------------------------------------


def _vocabulary(backend_name: str) -> dict:
    return rung_runner.load_protocol()["backends"][backend_name]["levers"]


def _refuse(cause: str, error: str, **facts: Any) -> dict:
    return {"status": "failure", "cause": cause, "facts": {"error": error, **facts}}


def _check_parameters(backend_name: str, params: dict) -> str | None:
    problems = rung_runner.plan_problems({"lever": "attempt", "parameters": params}, _vocabulary(backend_name))
    return "; ".join(problems) if problems else None


def _scratch(log: Path) -> Path:
    scratch = Path(log).parent / "router_scratch"
    scratch.mkdir(parents=True, exist_ok=True)
    return scratch


def pour_zones(board: str | Path) -> list[dict]:
    """Every copper pour of the board, from the RAW file, wherever it sits: top level or
    embedded in a footprint (every descendant node named ``zone``). A record has ``net``,
    ``layer``, ``filled_in_file`` (a stored ``filled_polygon`` anywhere inside the zone) and
    ``embedded_in`` (the footprint name, or None). A zone with a ``keepout`` child and no
    stored fill is a rule area and is left out; a ``keepout`` child can never hide stored
    fill: such a zone is listed as filled. Never ``Zone.is_filled`` (True for any
    ``(fill yes ...)``, which is how an outline-only pour was once misread as filled)."""
    from kicad_mcp import pour_step
    from kicad_tools.sexp import parse_file

    root = parse_file(str(board))
    table = pour_step._net_table(root)  # both file formats: net table or inline name
    out: list[dict] = []

    def walk(node: Any, footprint: str | None) -> None:
        for child in node.children:
            if child.name == "footprint":
                label = str(child.values[0]) if child.values and not hasattr(child.values[0], "children") else "?"
                walk(child, label)
            elif child.name == "zone":
                filled = any(n.name == "filled_polygon" for n in child.iter_all())
                if child.find("keepout") is not None and not filled:
                    continue
                layer = child.find("layer")
                layers = child.find("layers")
                first = (str(layer.values[0]) if layer is not None and layer.values
                         else (str(layers.values[0]) if layers is not None and layers.values else ""))
                out.append({
                    "net": pour_step._resolved_net(child, table) or "",
                    "layer": first,
                    "filled_in_file": filled,
                    "embedded_in": footprint,
                })
            else:
                walk(child, footprint)

    walk(root, None)
    return out


def _pour_problem(board: Path) -> str | None:
    """Refuse a board that carries a pour with STORED fill (archived backlog P4-06: neither router
    treats stored fill copper as an obstacle for a foreign net). A pour that is only an
    outline in the file (what the pour step writes: ``filled_in_file`` false) is allowed:
    there is no stored fill to be tracked through, and the gate refills before grading.
    Measured (ticket 23, KRT 0.22.0 + the real gate): routing a poured GND board produced
    no short and no clearance error under the refill. Provenance of an outline-only zone
    cannot be proven from the file (the pour step leaves no marker), so the rule is
    structural: outline-only is allowed whoever wrote it, stored fill is refused."""
    filled = [z for z in pour_zones(board) if z["filled_in_file"]]
    if not filled:
        return None
    zones = ", ".join(f"{z['net']}/{z['layer']}" for z in filled)
    return (f"board has {len(filled)} filled pour(s) with stored fill ({zones}); neither router "
            "treats stored fill as an obstacle (P4-06)")


# --- KiCadRoutingTools ----------------------------------------------------------------------------


def krt_backend() -> rung_runner.Backend:
    """Adapter for KiCadRoutingTools (the version `krt_cli_snapshot.json` pins) through the pinned wrapper."""

    def run(board: Path, params: dict, timeout_s: float, log: Path) -> dict:
        board = Path(board)
        problem = _check_parameters("krt", params)
        if problem:
            return _refuse("router-failure", f"lever outside the protocol table: {problem}")
        try:
            filled = _pour_problem(board)
        except Exception as exc:  # noqa: BLE001
            return _refuse("router-failure", f"could not inspect the board: {exc}")
        if filled:
            return _refuse("input-refused", filled)

        scratch = _scratch(log)
        routed = scratch / board.name
        escalation = params["escalation"]
        measured_started = time.monotonic()
        floors: dict = {}
        overrides: Path | None = None
        clearance_mm = None
        try:
            report = krt_tools.board_floor_overrides(board)
            floors = report["floors"]
            clearance_mm = floors.get("clearance")
            if escalation == "board" and floors:
                overrides = krt_tools.write_fab_overrides(floors, scratch / "board_floor_overrides.txt")
            advanced = {"--ordering": params["ordering"]} if params.get("ordering") else None
            run_record = krt_tools.run_kicad_routing_tools(
                board, routed, escalation=escalation, clearance_mm=clearance_mm,
                fab_overrides=overrides, grid_step_mm=params.get("grid_step_mm"),
                max_iterations=params.get("max_iterations"), timeout=max(1, math.ceil(timeout_s)),
                advanced_flags=advanced,
            )
        except krt_tools.KicadRoutingToolsTimeout as exc:
            return {"status": "timeout", "cause": "router-timeout", "router_elapsed_s": exc.elapsed_s,
                    "facts": {"error": str(exc)[:500], "timeout_s": exc.timeout}}
        except krt_tools.KicadRoutingToolsError as exc:
            return _refuse("router-failure", str(exc)[:1000])
        except Exception as exc:  # noqa: BLE001
            return _refuse("router-failure", f"{type(exc).__name__}: {exc}")
        measured_router_wall = time.monotonic() - measured_started

        try:
            delta = krt_tools.route_delta(board, routed)
            routing_toolset._apply_specs(board, delta["trace_specs"], delta["via_specs"])
        except Exception as exc:  # noqa: BLE001
            return _refuse("router-failure", f"could not diff or apply the routed copper: {exc}",
                           exit_code=run_record.get("exit_code"))

        router_log = run_record["log"]
        facts = {
            "exit_code": run_record["exit_code"],
            "elapsed_s": run_record["elapsed_s"],
            "router_version": run_record.get("router_version"),
            "version_check": run_record.get("version_check"),
            "strict_sizes_violated": bool(run_record.get("strict_sizes_violated")),
            "delivered_below_requested": run_record.get("delivered_below_requested", []),
            "logged_parameters": run_record.get("logged_parameters"),
            "board_floors": floors,
            "router_rewrote_project": bool(run_record.get("router_overwrote_project"))
            or bool(router_log.get("project_rule_writes")),
            "added_segments": len(delta["trace_specs"]),
            "added_vias": len(delta["via_specs"]),
            "removed_segment_count": delta.get("removed_segment_count"),
            "removed_via_count": delta.get("removed_via_count"),
            "fab_floor_relaxed": bool(router_log.get("fab_floor_relaxed")),
            "fab_tier_escalations": router_log.get("fab_tier_escalations"),
            "router_self_report": {  # the router's own claim: never evidence of connectivity
                "failed_nets": router_log.get("failed_nets"),
                "boxed_in_nets": router_log.get("boxed_in_nets"),
                "router_reported_nets": router_log.get("router_reported_nets"),
            },
        }
        # Router time only (the subprocess); loading, diffing and applying copper is overhead.
        # The cap is charged with the larger of what the wrapper reports and what this adapter
        # measured around the router call: a wrapper that under-reports cannot buy time.
        reported = run_record.get("elapsed_s")
        reported = float(reported) if isinstance(reported, (int, float)) else 0.0
        timing = {"router_elapsed_s": max(reported, measured_router_wall)}
        ok = run_record["exit_code"] in (0, krt_tools.STRICT_SIZES_EXIT_CODE)
        if ok:
            return {"status": "ok", "cause": None, "facts": facts, **timing}
        return {"status": "failure", "cause": "router-failure", "facts": facts, **timing}

    return run


# --- Freerouting ------------------------------------------------------------------------------------


def freerouting_backend() -> rung_runner.Backend:
    """Adapter for Freerouting (KiCad's DSN export, java -jar, KiCad's SES import, delta
    applied through the write layer). Availability is checked once more at the start of an
    attempt; callers should have reported the whole batch UNAVAILABLE before any attempt if
    it is not there."""

    def run(board: Path, params: dict, timeout_s: float, log: Path) -> dict:
        board = Path(board)
        problem = _check_parameters("freerouting", params)
        if problem:
            return _refuse("router-failure", f"lever outside the protocol table: {problem}")
        not_ready = _freerouting_ready()
        if not_ready:
            return _refuse("router-failure", f"Freerouting is not available: {not_ready}")
        try:
            filled = _pour_problem(board)
        except Exception as exc:  # noqa: BLE001
            return _refuse("router-failure", f"could not inspect the board: {exc}")
        if filled:
            return _refuse("input-refused", filled)

        # Build ticket 46: KiCad's own exporter writes the DSN and KiCad's own importer reads
        # the SES back, both in KiCad's bundled Python on scratch copies in a temporary
        # directory (the runner writes nowhere else; the run directory is not one); the DSN
        # and SES are kept beside the log for the audit trail. The board receives only the
        # routed copy's new copper, through the write layer's verified save.
        scratch = _scratch(log)
        with tempfile.TemporaryDirectory(prefix="kicad_mcp_freerouting_", ignore_cleanup_errors=True) as kicad_work:
            return _freerouting_round_trip(board, params, timeout_s, scratch, Path(kicad_work))

    return run


def _freerouting_round_trip(board: Path, params: dict, timeout_s: float, scratch: Path, work: Path) -> dict:
    ses = scratch / "board.ses"
    try:
        export = routing_toolset.export_dsn_with_kicad(board, work / "dsn")
    except routing_toolset.KicadSpecctraError as exc:
        return _refuse("router-failure", f"DSN export failed: {exc}"[:1000])
    try:  # the audit trail's copy; never a reason to fail the attempt
        shutil.copy(export["dsn_path"], scratch / "board.dsn")
        audit = None
    except OSError as exc:
        audit = f"the DSN was not kept beside the log: {exc}"
    started = time.monotonic()
    # Protocol 6 levers (build ticket 109): passed on only when the attempt sets them, and then
    # through the wrapper's allow-list (routing_toolset.freerouting_router_options).
    router_levers = {k: params[k] for k in ("fanout_enabled", "neck_width_um") if params.get(k) is not None}
    try:
        self_report = routing_toolset.run_freerouting(
            export["dsn_path"], ses, max_passes=params["max_passes"], timeout=max(1, math.ceil(timeout_s)),
            optimization_strategy=params.get("optimization_strategy"),
            selection_strategy=params.get("selection_strategy"),
            **router_levers,
        )
    except routing_toolset.FreeroutingTimeout as exc:
        return {"status": "timeout", "cause": "router-timeout", "router_elapsed_s": exc.elapsed_s,
                "facts": {"error": str(exc)[:500], "timeout_s": exc.timeout}}
    except routing_toolset.FreeroutingError as exc:
        return _refuse("router-failure", str(exc)[:1000])
    router_elapsed = time.monotonic() - started
    facts: dict[str, Any] = {
        "dsn_exporter": export["exporter"],
        # Freerouting's own score anti-correlates with real DRC (routing.py finding 7):
        # recorded for the audit trail, never read by the runner.
        "freerouting_self_report": self_report,
    }
    if audit:
        facts["dsn_audit_copy_error"] = audit
    try:
        imported = routing_toolset.import_ses_with_kicad(export, ses, work / "routed")
    except routing_toolset.KicadSpecctraError as exc:
        return {"status": "failure", "cause": "router-failure", "router_elapsed_s": router_elapsed,
                "facts": {**facts, "error": f"SES import failed: {exc}"[:1000], "code": getattr(exc, "code", None)}}
    facts.update({
        "added_segments": len(imported["trace_specs"]),
        "added_vias": len(imported["via_specs"]),
        "removed_copper": imported["removed_copper"],
        # ImportSpecctraSES returns True even when it skipped items: what it really did,
        # counted from the session and the board. The gate grades the result.
        "ses_import": imported["import"],
    })
    try:
        facts["write_check"] = routing_toolset._apply_specs(
            board, imported["trace_specs"], imported["via_specs"], expected_copper=imported["expected_copper"]
        )
    except Exception as exc:  # noqa: BLE001
        return {"status": "failure", "cause": "router-failure", "router_elapsed_s": router_elapsed,
                "facts": {**facts, "error": f"could not apply the routed copper: {exc}"[:1000],
                          "code": getattr(exc, "code", None)}}
    return {"status": "ok", "cause": None, "router_elapsed_s": router_elapsed, "facts": facts}


# --- under-width check (build ticket 36): one rule for every backend ----------------------------

# Half of KiCad's internal unit (1 nm): a value written as the requirement is never under it.
_UNDER_WIDTH_TOLERANCE_MM = 0.5e-6
_COPPER_ITEMS = ("segment", "arc", "via")


class UnderWidthCheckError(Exception):
    """The under-width check could not run; unknown is never evidence of none."""


def _copper_texts(board: Path) -> Counter:
    """Every segment, arc and via of the board as raw S-expression text (a multiset)."""
    from kicad_tools.sexp import parse_file

    root = parse_file(str(board))
    return Counter(c.to_string() for c in root.children if c.name in _COPPER_ITEMS)


def _project_rules(board: Path) -> dict:
    """The board's own ``.kicad_pro`` (net classes, their patterns and the board-wide
    minimums), read through ``board_rules``' reader. Without it there is nothing to judge
    against, so the check refuses instead of guessing."""
    from kicad_mcp import board_rules, pour_step

    project = board.with_suffix(".kicad_pro")
    if not project.is_file():
        raise UnderWidthCheckError(f"no project file {project.name} beside the board: the net classes "
                                   "the under-width check judges against are unknown")
    data = board_rules._read_project(project)
    if not isinstance(data, dict):
        raise UnderWidthCheckError(f"{project.name} did not parse to a JSON object")
    _resolvable(data, pour_step.board_net_names(board))
    return data


def _resolvable(data: dict, nets=()) -> None:
    """A net-class pattern outside the allowlist ``board_rules._pattern_syntax_problem``, or a net KiCad
    would class through its bus members (``board_rules._bus_member_refusal``), leaves a net's
    requirement unknown: the check refuses instead of judging against a guessed class."""
    from kicad_mcp import board_rules

    try:
        board_rules._check_patterns(data)
        for net in sorted(nets):
            board_rules._netclass_chain(data, net)
    except board_rules.UnsupportedNetclassPattern as exc:
        raise UnderWidthCheckError(str(exc)) from exc


def _raw_mm(node: Any, token: str) -> float:
    child = node.find(token)
    if child is None or not child.values:
        raise UnderWidthCheckError(f"{node.name} without ({token} ...): {node.to_string()[:200]}")
    try:
        value = float(child.values[0])
    except (TypeError, ValueError):
        raise UnderWidthCheckError(f"{node.name} with a non-numeric ({token} ...): {node.to_string()[:200]}") from None
    if not math.isfinite(value):
        raise UnderWidthCheckError(f"{node.name} with a non-finite ({token} ...): {node.to_string()[:200]}")
    return value


def _raw_xy(node: Any, token: str) -> list[float] | None:
    child = node.find(token)
    if child is None or len(child.values) < 2:
        return None
    try:
        return [float(child.values[0]), float(child.values[1])]
    except (TypeError, ValueError):
        return None


def _requirement(data: dict, net: str, class_key: str, rule_key: str | None) -> tuple[float, str]:
    """``(required_mm, required_from)``: the value KiCad's net-class resolution gives ``net``
    (``board_rules._net_value``: the first matching class that defines the key, then Default)
    and the board-wide minimum, whichever is larger."""
    from kicad_mcp import board_rules

    candidates: list[tuple[float, str]] = []
    class_value, supplier = board_rules._net_value(data, net, class_key)
    if class_value is not None:
        candidates.append((class_value, f"netclass {supplier} {class_key}"))
    if rule_key is not None:
        floor, _source = board_rules._constraint_before(data, rule_key)
        if floor is not None:
            candidates.append((float(floor), f"rules.{rule_key}"))
    if not candidates:
        raise UnderWidthCheckError(f"net {net!r}: no net class defines {class_key} and the board has no "
                                   f"{rule_key or 'minimum'}: nothing to judge against")
    # Ties go to the net class: it is what was requested.
    return max(candidates, key=lambda c: (c[0], c[1].startswith("netclass")))


def under_width_items(board: str | Path, before: Counter, project: dict) -> tuple[list[dict], int]:
    """``(items, checked)``: every segment, arc and via on ``board`` that is not in ``before``
    (the attempt's input copper, raw text) and is narrower than its net class asks, read
    from the RAW S-expression: a track's ``(width ...)``, a via's ``(size ...)`` and
    ``(drill ...)``. Never a router's report, never a ``kicad_tools`` convenience property.

    The requirement is the net's value from the board's own ``.kicad_pro`` as KiCad resolves
    it (``board_rules._net_value``: composite classes per key, wildcard or regex patterns;
    a pattern outside the syntax allowlist raises ``UnderWidthCheckError``;
    ``track_width``; ``via_diameter``/``via_drill``, or the ``microvia_*`` pair for a micro
    via), raised to the board-wide minimum where that is larger (``min_track_width``,
    ``min_via_diameter``, ``min_through_hole_diameter``, ``min_microvia_*``; an absent key
    is KiCad's measured default where one was measured). Custom ``.kicad_dru`` constraints are DRC constraints the gate grades."""
    from kicad_mcp import board_rules, pour_step
    from kicad_tools.sexp import parse_file

    _resolvable(project)
    root = parse_file(str(board))
    table = pour_step._net_table(root)
    remaining = Counter(before)
    items: list[dict] = []
    checked = 0
    for node in root.children:
        if node.name not in _COPPER_ITEMS:
            continue
        text = node.to_string()
        if remaining[text] > 0:  # input copper, not this attempt's delivery
            remaining[text] -= 1
            continue
        checked += 1
        net = pour_step._resolved_net(node, table)
        if net is None:
            raise UnderWidthCheckError(f"{node.name} on a net the board does not define: {text[:200]}")
        netclass = board_rules._effective_netclass(project, net)  # KiCad's name: "A,B"
        if node.name == "via":
            micro = any(str(v) == "micro" for v in node.values if not hasattr(v, "children"))
            prefix, floors = ("microvia", ("min_microvia_diameter", "min_microvia_drill")) if micro else (
                "via", ("min_via_diameter", "min_through_hole_diameter"))
            layers = node.find("layers")
            layer = "-".join(str(v) for v in layers.values) if layers is not None else None
            checks = [("diameter", "size", f"{prefix}_diameter", floors[0]),
                      ("drill", "drill", f"{prefix}_drill", floors[1])]
            kind, where = ("microvia" if micro else "via"), {"at": _raw_xy(node, "at")}
        else:
            layer_node = node.find("layer")
            layer = str(layer_node.values[0]) if layer_node is not None and layer_node.values else None
            checks = [("width", "width", "track_width", "min_track_width")]
            kind = "track" if node.name == "segment" else "arc"
            where = {"start": _raw_xy(node, "start"), "end": _raw_xy(node, "end")}
        for dimension, token, class_key, rule_key in checks:
            delivered = _raw_mm(node, token)
            required, source = _requirement(project, net, class_key, rule_key)
            if delivered < required - _UNDER_WIDTH_TOLERANCE_MM:
                items.append({"net": net, "netclass": netclass, "kind": kind, "layer": layer,
                              "dimension": dimension, "delivered_mm": delivered, "required_mm": required,
                              "required_from": source, **where})
    return items, checked


# --- necked pad entry (protocol 6, build ticket 109) ---------------------------------------------
#
# The owner's decision of ticket 108 (evidence: research ticket 107): a track narrower than its net
# class is a FORCED NECK, not an under-width fail, only if (1) the pad geometry forces it (the class
# width plus the class clearance cannot fit between the neighbouring pads: w > s + 2 (g - c)),
# (2) its width is at or above the board minimum, (3) it lies within the protocol's length bound from
# the pad edge, and (4) it is counted and labelled "PASS (necked)" (the runner does that). Everything
# below reads the raw S-expressions of the graded board; no kicad_tools convenience property.

_NECK_NODE_TOL_MM = 1e-4  # two track ends closer than this are one node (routers write 4 to 6 decimals)
_NECK_FORCE_TOL_MM = 1e-6
_NECK_NEIGHBOUR_REACH_MM = 3.0  # an unreadable pad this close to a contact pad stops the judgement


def necked_pad_entry_policy() -> dict:
    """The protocol's ``policies.necked_pad_entry`` (label and length bound)."""
    return dict(rung_runner.load_protocol()["policies"]["necked_pad_entry"])


def _kicad_rot(x: float, y: float, degrees: float) -> tuple[float, float]:
    """KiCad's rotation of a footprint-local vector (the formula ``pour_step._pad_records`` uses)."""
    a = math.radians(degrees)
    c, s = math.cos(a), math.sin(a)
    return x * c + y * s, -x * s + y * c


class _NeckPad:
    """One copper pad from its raw ``(pad ...)`` node: world centre, board-absolute angle, the local
    bounding box of its copper, and the copper layers it is on. ``box`` is ``None`` when the shape
    cannot be read (a flipped footprint, a custom pad with a primitive other than ``gr_poly``, a
    trapezoid): such a pad never forces a neck and, near a contact pad, stops the judgement."""

    __slots__ = ("ref", "number", "net", "layers", "centre", "angle", "box")

    def __init__(self, ref, number, net, layers, centre, angle, box):
        self.ref, self.number, self.net, self.layers = ref, number, net, layers
        self.centre, self.angle, self.box = centre, angle, box

    @property
    def name(self) -> str:
        return f"{self.ref}.{self.number}"

    def to_world(self, lx: float, ly: float) -> tuple[float, float]:
        rx, ry = _kicad_rot(lx, ly, self.angle)
        return self.centre[0] + rx, self.centre[1] + ry

    def to_local(self, x: float, y: float) -> tuple[float, float]:
        return _kicad_rot(x - self.centre[0], y - self.centre[1], -self.angle)

    def corners(self) -> list[tuple[float, float]]:
        x0, y0, x1, y1 = self.box
        return [self.to_world(x0, y0), self.to_world(x1, y0), self.to_world(x1, y1), self.to_world(x0, y1)]

    def contains(self, point: tuple[float, float]) -> bool:
        lx, ly = self.to_local(*point)
        x0, y0, x1, y1 = self.box
        tol = _NECK_NODE_TOL_MM
        return x0 - tol <= lx <= x1 + tol and y0 - tol <= ly <= y1 + tol

    def inside_length(self, a: tuple[float, float], b: tuple[float, float]) -> float:
        """Length of the segment ``a``-``b`` inside this pad's box (Liang-Barsky in the pad frame)."""
        (ax, ay), (bx, by) = self.to_local(*a), self.to_local(*b)
        x0, y0, x1, y1 = self.box
        t0, t1 = 0.0, 1.0
        for p, q in ((-(bx - ax), ax - x0), (bx - ax, x1 - ax), (-(by - ay), ay - y0), (by - ay, y1 - ay)):
            if abs(p) < 1e-12:
                if q < 0:
                    return 0.0
                continue
            r = q / p
            if p < 0:
                t0 = max(t0, r)
            else:
                t1 = min(t1, r)
            if t0 > t1:
                return 0.0
        return (t1 - t0) * math.dist(a, b)


def _pad_local_box(pad: Any) -> tuple[float, float, float, float] | None:
    """The bounding box of a pad's copper in the pad's own frame, from its raw shape, ``(size)``,
    ``(options (anchor ...))`` and ``(primitives (gr_poly (pts ...) (width ..)))``; ``None`` for a shape
    this check does not read."""
    shape = str(pad.values[2]) if len(pad.values) > 2 else ""
    size = pad.find("size")
    if size is None or len(size.values) < 2:
        return None
    sx, sy = float(size.values[0]), float(size.values[1])
    if shape in ("rect", "roundrect", "oval"):
        return (-sx / 2, -sy / 2, sx / 2, sy / 2)
    if shape == "circle":
        return (-sx / 2, -sx / 2, sx / 2, sx / 2)
    if shape != "custom":
        return None
    options = pad.find("options")
    anchor = options.find("anchor") if options is not None else None
    kind = str(anchor.values[0]) if anchor is not None and anchor.values else ""
    if kind == "circle":
        box = [-sx / 2, -sx / 2, sx / 2, sx / 2]
    elif kind == "rect":
        box = [-sx / 2, -sy / 2, sx / 2, sy / 2]
    else:
        return None
    primitives = pad.find("primitives")
    for prim in primitives.children if primitives is not None else []:
        if prim.name != "gr_poly":
            return None
        pts = prim.find("pts")
        stroke = prim.find("width")
        half = float(stroke.values[0]) / 2 if stroke is not None and stroke.values else 0.0
        for xy in pts.find_all("xy") if pts is not None else []:
            x, y = float(xy.values[0]), float(xy.values[1])
            box = [min(box[0], x - half), min(box[1], y - half), max(box[2], x + half), max(box[3], y + half)]
    return (box[0], box[1], box[2], box[3])


def _neck_pads(root: Any, copper: list[str]) -> list[_NeckPad]:
    """Every copper pad of the board from raw nodes (position as ``pour_step._pad_records``)."""
    from kicad_mcp import pour_step

    table = pour_step._net_table(root)
    pads: list[_NeckPad] = []
    for fp in (c for c in root.children if c.name == "footprint"):
        fat = fp.find("at")
        fx, fy = (float(fat.values[0]), float(fat.values[1])) if fat is not None else (0.0, 0.0)
        frot = float(fat.values[2]) if fat is not None and len(fat.values) > 2 else 0.0
        layer = fp.find("layer")
        flipped = layer is None or not layer.values or str(layer.values[0]) != "F.Cu"
        ref = pour_step._footprint_reference(fp)
        for pad in fp.find_all("pad"):
            on: set[str] = set()
            layers_node = pad.find("layers")
            for token in layers_node.values if layers_node is not None else []:
                on.update(krt_tools._expand_layer_token(str(token), copper))
            if not on:
                continue  # paste, mask or hole only: no copper
            at = pad.find("at")
            px, py = (float(at.values[0]), float(at.values[1])) if at is not None else (0.0, 0.0)
            rx, ry = _kicad_rot(px, py, frot)
            # A pad's own angle is stored board-absolute, footprint rotation included (CLAUDE.md, hard rule 1).
            angle = float(at.values[2]) if at is not None and len(at.values) > 2 else 0.0
            box = None if flipped else _pad_local_box(pad)
            pads.append(_NeckPad(ref, str(pad.values[0]) if pad.values else "",
                                 pour_step._resolved_net(pad, table) or "", on, (fx + rx, fy + ry), angle, box))
    return pads


def _projection(points: list[tuple[float, float]], axis: tuple[float, float]) -> tuple[float, float]:
    values = [p[0] * axis[0] + p[1] * axis[1] for p in points]
    return min(values), max(values)


def _entry_limit(contact: _NeckPad, direction: tuple[float, float], pads: list[_NeckPad], layer: str,
                 project: dict) -> float:
    """The widest track that fits through ``contact`` entered along ``direction`` (a unit vector out of
    the pad): the owner's ``w <= s + 2 (g - c)``, the smallest over the neighbouring pads of other nets
    that sit beside it (their extent along the entry direction overlaps the pad's). ``s`` is the pad's
    width across the entry direction, ``g`` the gap to the neighbour across it and ``c`` the larger of
    the two nets' class clearances. ``inf`` when nothing sits beside the pad. An unreadable pad within
    reach raises ``UnderWidthCheckError``: unknown is never evidence of room."""
    across = (-direction[1], direction[0])
    corners = contact.corners()
    d_lo, d_hi = _projection(corners, direction)
    n_lo, n_hi = _projection(corners, across)
    c_own = _requirement(project, contact.net, "clearance", "min_clearance")[0]
    best = math.inf
    for other in pads:
        if other is contact or other.net == contact.net or layer not in other.layers:
            continue
        if other.box is None:
            if math.dist(other.centre, contact.centre) < _NECK_NEIGHBOUR_REACH_MM:
                raise UnderWidthCheckError(f"pad {other.name} next to {contact.name} has a shape or footprint "
                                           "side this check does not read: no neck can be judged there")
            continue
        corners_o = other.corners()
        o_d_lo, o_d_hi = _projection(corners_o, direction)
        if min(d_hi, o_d_hi) - max(d_lo, o_d_lo) <= _NECK_FORCE_TOL_MM:
            continue  # in front of or behind the entry, not beside it
        o_n_lo, o_n_hi = _projection(corners_o, across)
        gap = max(o_n_lo - n_hi, n_lo - o_n_hi, 0.0)
        c_other = _requirement(project, other.net, "clearance", "min_clearance")[0] if other.net else c_own
        best = min(best, (n_hi - n_lo) + 2.0 * (gap - max(c_own, c_other)))
    return best


def _neck_network(root: Any, table: dict, pads: list[_NeckPad], project: dict, net: str, layer: str) -> dict:
    """The straight tracks of one net on one layer as a graph, the pad entries that FORCE a neck (the
    class width does not fit through them) and each node's distance from the nearest forcing pad's edge
    along the tracks (the part of a track inside the pad does not count; full-width copper counts)."""
    import heapq

    from kicad_mcp import pour_step

    class_width = _requirement(project, net, "track_width", "min_track_width")[0]
    nodes: list[tuple[float, float]] = []

    def node(point: tuple[float, float]) -> int:
        for i, known in enumerate(nodes):
            if abs(known[0] - point[0]) <= _NECK_NODE_TOL_MM and abs(known[1] - point[1]) <= _NECK_NODE_TOL_MM:
                return i
        nodes.append(point)
        return len(nodes) - 1

    segments: list[tuple[int, int, tuple[float, float], tuple[float, float]]] = []
    for child in root.children:
        if child.name != "segment":
            continue
        layer_node = child.find("layer")
        if (layer_node is None or not layer_node.values or str(layer_node.values[0]) != layer
                or pour_step._resolved_net(child, table) != net):
            continue
        a, b = _raw_xy(child, "start"), _raw_xy(child, "end")
        if a is None or b is None:
            continue
        a, b = (a[0], a[1]), (b[0], b[1])
        segments.append((node(a), node(b), a, b))

    entries: list[dict] = []
    trims: list[float] = [0.0] * len(segments)
    start: dict[int, dict] = {}
    for pad in pads:
        if pad.net != net or layer not in pad.layers or pad.box is None:
            continue
        for index, (i, j, a, b) in enumerate(segments):
            for end_node, end, other in ((i, a, b), (j, b, a)):
                length = math.dist(a, b)
                if length <= _NECK_NODE_TOL_MM or not pad.contains(end):
                    continue
                direction = ((other[0] - end[0]) / length, (other[1] - end[1]) / length)
                limit = _entry_limit(pad, direction, pads, layer, project)
                if class_width > limit + _NECK_FORCE_TOL_MM:
                    entry = {"pad": pad.name, "limit": limit}
                    entries.append(entry)
                    start.setdefault(end_node, entry)
                    trims[index] = max(trims[index], pad.inside_length(a, b))

    cost = [max(0.0, math.dist(a, b) - trims[k]) for k, (_i, _j, a, b) in enumerate(segments)]
    adjacent: dict[int, list[tuple[int, float]]] = {}
    for k, (i, j, _a, _b) in enumerate(segments):
        adjacent.setdefault(i, []).append((j, cost[k]))
        adjacent.setdefault(j, []).append((i, cost[k]))
    dist: dict[int, float] = {}
    source: dict[int, dict] = {}
    queue = [(0.0, n) for n in start]
    for n, entry in start.items():
        source[n] = entry
    heapq.heapify(queue)
    while queue:
        d, n = heapq.heappop(queue)
        if n in dist:
            continue
        dist[n] = d
        for m, w in adjacent.get(n, ()):
            if m not in dist:
                heapq.heappush(queue, (d + w, m))
                source.setdefault(m, source[n])
    return {"nodes": nodes, "node": node, "entries": entries, "dist": dist, "source": source}


def classify_necks(board: str | Path, items: list[dict], project: dict, *,
                   max_length_mm: float | None = None) -> list[dict]:
    """``items`` (``under_width_items``) with each item's neck verdict added: ``neck_verdict`` is
    ``"necked"`` (a forced neck under the owner's four limits; counted, never a plain PASS) or
    ``"fail"``; ``neck_reason`` says which limit failed (``not_a_straight_track``,
    ``below_board_minimum``, ``not_forced_by_pad_geometry``, ``neck_longer_than_bound``) or is
    ``forced_neck``. A necked item also carries ``neck_pad``, ``neck_pad_limit_mm``,
    ``neck_distance_mm`` (its far end's distance from the pad edge along the net's straight tracks),
    ``neck_bound_mm`` and ``length_mm``. ``max_length_mm`` defaults to the protocol's bound. A pad the
    check cannot read next to a contact pad raises ``UnderWidthCheckError`` (the attempt is not judged)."""
    from kicad_mcp import board_rules, pour_step
    from kicad_tools.sexp import parse_file

    bound = float(max_length_mm if max_length_mm is not None
                  else necked_pad_entry_policy()["max_length_beyond_pad_mm"])
    root = parse_file(str(board))
    table = pour_step._net_table(root)
    floor, _source = board_rules._constraint_before(project, "min_track_width")
    out = [dict(item) for item in items]
    pads: list[_NeckPad] | None = None
    networks: dict[tuple[str, str], dict] = {}

    for item in out:
        if item["kind"] != "track" or item["dimension"] != "width" or not item.get("start") or not item.get("end"):
            item.update(neck_verdict="fail", neck_reason="not_a_straight_track")  # via, microvia or arc
            continue
        if floor is not None and item["delivered_mm"] < floor - _UNDER_WIDTH_TOLERANCE_MM:
            item.update(neck_verdict="fail", neck_reason="below_board_minimum", board_minimum_mm=floor)
            continue
        if pads is None:
            pads = _neck_pads(root, krt_tools.board_pour_info(board)["copper_layers"])
        key = (item["net"], item["layer"])
        if key not in networks:
            networks[key] = _neck_network(root, table, pads, project, *key)
        network = networks[key]
        ends = [network["node"](tuple(item["start"])), network["node"](tuple(item["end"]))]
        far_node = max(ends, key=lambda n: network["dist"].get(n, math.inf))
        far = network["dist"].get(far_node, math.inf)
        if math.isinf(far):  # no pad entry that forces a neck reaches this copper along the net's tracks
            item.update(neck_verdict="fail", neck_reason="not_forced_by_pad_geometry")
        elif far > bound + _NECK_FORCE_TOL_MM:
            item.update(neck_verdict="fail", neck_reason="neck_longer_than_bound", neck_bound_mm=bound,
                        neck_distance_mm=far)
        else:
            entry = network["source"][far_node]
            item.update(neck_verdict="necked", neck_reason="forced_neck", neck_pad=entry["pad"],
                        neck_pad_limit_mm=entry["limit"], neck_distance_mm=far, neck_bound_mm=bound,
                        length_mm=math.dist(item["start"], item["end"]))
    return out


def _not_judged(outcome: dict, facts: dict, check_error: str, error: str) -> dict:
    """The check could not run: recorded, and an attempt the router reported ``ok`` fails
    (``router-failure``); unknown is never evidence of none. A failed attempt stays failed."""
    facts["under_width_check"] = {"ran": False, "error": check_error}
    if outcome.get("status", "ok") == "ok":
        facts.setdefault("error", error)
        return {**outcome, "status": "failure", "cause": "router-failure", "facts": facts}
    return {**outcome, "facts": facts}


# The KRT ledger kinds the raw board check judges (a track's width, a via's diameter and drill).
_RAW_CHECKED_LEDGER_KINDS = frozenset({"track_width", "via_diameter", "via_drill"})


def _clear_stale_strict_sizes_flag(facts: dict, items: list) -> None:
    """KRT's ``--strict-sizes`` exit 3 reads its ledger of necking events, not the board it
    ships: its post passes (cycle prune, smoothing, collinear merges) remove or replace necked
    segments, and the ledger keeps the entry. Measured on the rung-2 batch of 2026-10-19
    (build ticket 37): four 0.326 mm rows on one net, every shipped segment 0.5 or 0.8 mm.

    The raw board check is the evidence (CLAUDE.md rule 2). The flag is therefore cleared, with
    the router's claim kept as ``strict_sizes_reported_by_router``, only when all of this holds:
    the raw check found nothing, the CLI exited 3, KRT listed at least one row and every row is
    a kind the raw check judges, and no fab-tier escalation fired (a descent of a kind the raw
    width check cannot see). Anything else, an exit 3 nobody can explain included, stays a hit."""
    if not facts.get("strict_sizes_violated") or items:
        return
    rows = facts.get("router_reported_below_requested")
    if (
        facts.get("exit_code") != 3
        or facts.get("fab_tier_escalations") != 0
        or not isinstance(rows, list)
        or not rows
        or not all(isinstance(r, dict) and r.get("kind") in _RAW_CHECKED_LEDGER_KINDS for r in rows)
    ):
        return
    facts["strict_sizes_reported_by_router"] = True
    facts["strict_sizes_violated"] = False


def with_under_width_check(backend: rung_runner.Backend) -> rung_runner.Backend:
    """The one place every backend's result passes the under-width rule (build ticket 36).

    Before the router runs, the board's input copper and its ``.kicad_pro`` are read; after
    it, every piece of copper the attempt added to the GRADED board is checked
    (``under_width_items``). The result replaces ``facts["delivered_below_requested"]``,
    which the runner's policy reads; whatever the backend reported there itself moves to
    ``facts["router_reported_below_requested"]`` (audit trail only). KRT's own
    ``strict_sizes_violated`` stays as it was. A check that cannot run (no board left after
    the backend, or a delivery it cannot read) fails an attempt the router reported ``ok``:
    unknown is never evidence of none. A project or input copper it cannot read refuses the
    attempt before the router runs (``input-refused``), and so does a net-class pattern outside
    the syntax allowlist (``board_rules._check_patterns``)
    or a board net KiCad would class through its bus members (``board_rules._bus_member_refusal``)."""

    def run(board: Path, params: dict, timeout_s: float, log: Path) -> dict:
        board = Path(board)
        try:
            project = _project_rules(board)
            before = _copper_texts(board)
        except Exception as exc:  # noqa: BLE001 - the attempt is refused, not crashed
            return _refuse("input-refused", f"under-width check cannot read the board's rules or copper: {exc}"[:1000],
                           under_width_check={"ran": False, "error": f"{type(exc).__name__}: {exc}"[:500]})
        outcome = backend(board, params, timeout_s, log)
        if not isinstance(outcome, dict):
            return outcome  # the runner reports a malformed backend result itself
        facts = dict(outcome["facts"]) if isinstance(outcome.get("facts"), dict) else {}
        if "delivered_below_requested" in facts:
            facts["router_reported_below_requested"] = facts.pop("delivered_below_requested")
        if not board.exists():
            return _not_judged(outcome, facts, "no board after the backend ran", "no board after the backend ran")
        try:
            items, checked = under_width_items(board, before, project)
            items = classify_necks(board, items, project)
        except Exception as exc:  # noqa: BLE001
            error = f"under-width check could not run: {type(exc).__name__}: {exc}"[:1000]
            return _not_judged(outcome, facts, error, error)
        failing = [i for i in items if i.get("neck_verdict") != "necked"]
        necked = [i for i in items if i.get("neck_verdict") == "necked"]
        facts["delivered_below_requested"] = items  # every narrower-than-class item, each with its neck verdict
        _clear_stale_strict_sizes_flag(facts, failing)
        facts["under_width_check"] = {
            "ran": True, "checked": checked, "under_width": len(items), "failing": len(failing),
            "necked": len(necked), "necked_length_mm": sum(i["length_mm"] for i in necked),
            "necked_pad_entry_bound_mm": necked_pad_entry_policy()["max_length_beyond_pad_mm"],
            "source": "raw (segment|arc|via ...) nodes of the graded board against its .kicad_pro "
                      "net classes and board-wide minimums; raw pad nodes for the neck verdicts",
        }
        return {**outcome, "facts": facts}

    run.__wrapped__ = backend  # type: ignore[attr-defined]
    run.under_width_checked = True  # type: ignore[attr-defined]
    return run


_BACKEND_FACTORIES: dict[str, Callable[[], rung_runner.Backend]] = {
    "krt": krt_backend,
    "freerouting": freerouting_backend,
}


def make_backend(backend_name: str) -> Callable[..., dict]:
    """A real backend, always behind the shared under-width check."""
    factory = _BACKEND_FACTORIES.get(backend_name)
    if factory is None:
        raise ValueError(f"unknown backend {backend_name!r}")
    return with_under_width_check(factory())
