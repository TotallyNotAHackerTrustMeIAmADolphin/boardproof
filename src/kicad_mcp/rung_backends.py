"""The real backends behind the rung runner's backend seam.

Contract of the seam (``rung_runner``): ``backend(board, parameters, timeout_s, log)``
mutates ``board`` (a fresh copy of the frozen input) in place and returns
``{"status": "ok" | "timeout" | "failure", "cause": str | None, "facts": {...}}``.
``facts`` is audit-trail material (exit code, router version, the router's own
self-report). The gate's verdict decides. The runner reads ``facts`` for the protocol's
delivered-below-requested policy (``delivered_below_requested``, ``strict_sizes_violated``),
which can fail an attempt, never pass one, and reports ``removed_segment_count`` and
``removed_via_count`` as the attempt's ``removed_copper``; the rest it keeps unread as
``router_facts``.

That policy's evidence is one check for every backend (build ticket 36):
``make_backend`` puts each adapter behind ``with_under_width_check``, which judges the
copper the attempt added to the graded board from its raw S-expressions against the
board's own net classes (resolved as KiCad does) and writes
``facts["delivered_below_requested"]``. A router's own report never replaces it.

Both adapters go through the existing product path: the router runs on a scratch copy,
its added copper is diffed out through ``kicad_tools`` and applied to the board
(the same ``route_delta`` plus ``_apply_specs`` that ``confirm_route`` uses), so the
router's own writer never becomes the board that gets graded and the board's project
files are never touched. Scratch output and logs live beside the attempt log, outside
the project directory.

Parameters are the pre-declared discrete levers of ``autonomy_protocol.json`` and
nothing else: an unknown key or a value outside the table is a failed attempt.
"""

